# ══════════════════════════════════════════════════════════════════════════════
def main():
    print(f"\nSearching ROOT files in : {BUILD_DIR}")
    print(f"Saving plots to         : {PLOT_DIR}")
    print(f"Graphene thickness      : {GRAPHENE_UM} µm (fixed)")
    print(f"Selected fraction       : {SELECTED_FRACTION*100:.1f} %\n")

    data_by_fraction: dict = {}
    for frac in BORON_FRACTIONS:
        label = f"output_{root_name(frac)}"
        print(f"  Reading {root_name(frac)} ...", end=" ")
        data = load_root(frac)
        if data is not None:
            data_by_fraction[frac] = data
            print(f"OK  |  ProductosCaptura: {len(data['captura']):6d}"
                  f"  |  ParticulasDetector: {len(data['detector']):6d}")
        else:
            print("NOT AVAILABLE")

    if not data_by_fraction:
        sys.exit("\n[ERROR] No ROOT files found. Run run_simulations_boron.py first.")

    df = compute_metrics(data_by_fraction)

    # ── Console table ──────────────────────────────────────────────────────────
    print("\n" + "="*85)
    print(f"{'Boron %':>10}  {'Eff.%':>7}  "
          f"{'α_created':>10}  {'Li7_cre':>8}  {'γ_cre':>8}  "
          f"{'α_det':>7}  {'Li7_det':>7}  {'γ_det':>7}")
    print("-"*85)
    for _, row in df.iterrows():
        print(f"{row['boron_pct']:>8.2f} %   "
              f"{row['efficiency_%']:>6.3f}%  "
              f"{row['created_alpha']:>10.0f}  "
              f"{row['created_Li7']:>8.0f}  "
              f"{row['created_gamma']:>8.0f}  "
              f"{row['det_alpha']:>7.0f}  "
              f"{row['det_Li7']:>7.0f}  "
              f"{row['det_gamma']:>7.0f}")
    print("="*85 + "\n")

    csv_path = PLOT_DIR / "metrics_boron.csv"
    df.to_csv(csv_path, index=False, float_format="%.4f")
    print(f"  [CSV]  Table saved to {csv_path.name}\n")

    print("Generating plots...")
    plot_efficiency(df)
    plot_created_particles(df)
    plot_detected_particles(df)
    plot_transmission_fraction(df)
    plot_creation_spectra(data_by_fraction)
